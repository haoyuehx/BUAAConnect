//go:build linux

package runtime

import (
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// ProcessInfo collects identifiers used to verify process ownership.
type ProcessInfo struct {
	PID       int
	StartTime uint64
	CmdLine   string
}

// SelfInfo returns the current process identifiers.
func SelfInfo() (*ProcessInfo, error) {
	pid := os.Getpid()
	startTime, err := processStartTime(pid)
	if err != nil {
		return nil, err
	}
	cmdline, err := readCmdline(pid)
	if err != nil {
		return nil, err
	}
	return &ProcessInfo{PID: pid, StartTime: startTime, CmdLine: programBase(cmdline)}, nil
}

// IsSameProgram reports whether the running process with pid matches the
// recorded process identifiers. It never treats a stale PID as belonging to
// this program.
func IsSameProgram(pid int, recordedStartTime uint64, recordedCmdline string) bool {
	if pid <= 0 {
		return false
	}
	startTime, err := processStartTime(pid)
	if err != nil {
		return false
	}
	if startTime != recordedStartTime {
		return false
	}
	cmdline, err := readCmdline(pid)
	if err != nil {
		return false
	}
	// Compare basename or full command line. Be tolerant of path differences.
	return cmdline == recordedCmdline || sameProgramName(cmdline, recordedCmdline)
}

// processStartTime reads the starttime field (field 22, 1-indexed) from
// /proc/<pid>/stat. It is the clock ticks since boot, stable for the lifetime
// of the process and unique enough for ownership verification.
func processStartTime(pid int) (uint64, error) {
	path := fmt.Sprintf("/proc/%d/stat", pid)
	data, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	return parseProcStatStartTime(data)
}

// parseProcStatStartTime extracts the starttime value from the contents of
// /proc/<pid>/stat. After splitting on the closing ')' of the comm field,
// starttime is the 20th field after comm (zero-indexed fields[19]).
func parseProcStatStartTime(data []byte) (uint64, error) {
	// The command name in parentheses may contain spaces and parentheses,
	// so locate the last ')' before splitting fields.
	end := bytes.LastIndexByte(data, ')')
	if end < 0 {
		return 0, fmt.Errorf("malformed /proc stat data")
	}
	fields := strings.Fields(string(data[end+1:]))
	// starttime is the 20th field after the comm field (fields[19]).
	if len(fields) < 20 {
		return 0, fmt.Errorf("insufficient fields in /proc stat data")
	}
	return strconv.ParseUint(fields[19], 10, 64)
}

func readCmdline(pid int) (string, error) {
	data, err := os.ReadFile(fmt.Sprintf("/proc/%d/cmdline", pid))
	if err != nil {
		return "", err
	}
	return strings.ReplaceAll(string(data), "\x00", " "), nil
}

func sameProgramName(a, b string) bool {
	nameA := programBase(a)
	nameB := programBase(b)
	return nameA != "" && nameA == nameB
}

func programBase(cmdline string) string {
	if cmdline == "" {
		return ""
	}
	fields := strings.Fields(cmdline)
	if len(fields) == 0 {
		return ""
	}
	base := fields[0]
	if i := strings.LastIndex(base, "/"); i >= 0 {
		base = base[i+1:]
	}
	// Strip common Go binary suffixes generated by "go run" / "go test".
	for _, suffix := range []string{".test", ".exe"} {
		base = strings.TrimSuffix(base, suffix)
	}
	// Match buaaconnect, zju-connect, or the test binary name.
	for _, candidate := range []string{"buaaconnect", "zju-connect", "buaa"} {
		if strings.Contains(strings.ToLower(base), candidate) {
			return candidate
		}
	}
	return base
}
