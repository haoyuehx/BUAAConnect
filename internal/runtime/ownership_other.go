//go:build !linux

package runtime

import (
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"strings"
)

// ProcessInfo collects identifiers used to verify process ownership.
type ProcessInfo struct {
	PID       int
	StartTime uint64
	CmdLine   string
}

// SelfInfo returns the current process identifiers.
func SelfInfo() (*ProcessInfo, error) {
	pid := os.Getpid()
	cmdline, err := readCmdline(pid)
	if err != nil {
		return nil, err
	}
	return &ProcessInfo{PID: pid, StartTime: uint64(os.Getpid()), CmdLine: programBase(cmdline)}, nil
}

// IsSameProgram reports whether the running process with pid matches the
// recorded identifiers. On non-Linux platforms it uses ps as a best-effort
// check and falls back to checking that the process exists.
func IsSameProgram(pid int, recordedStartTime uint64, recordedCmdline string) bool {
	if pid <= 0 {
		return false
	}
	if runtime.GOOS == "windows" {
		// Best-effort: check process existence only.
		proc, err := os.FindProcess(pid)
		if err != nil {
			return false
		}
		_ = proc.Release()
		return true
	}
	cmdline, err := readCmdline(pid)
	if err != nil {
		return false
	}
	return cmdline == recordedCmdline || sameProgramName(cmdline, recordedCmdline)
}

func readCmdline(pid int) (string, error) {
	out, err := exec.Command("ps", "-p", fmt.Sprintf("%d", pid), "-o", "command=").CombinedOutput()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func programBase(cmdline string) string {
	if cmdline == "" {
		return ""
	}
	fields := strings.Fields(cmdline)
	if len(fields) == 0 {
		return ""
	}
	base := fields[0]
	if i := strings.LastIndex(base, "/"); i >= 0 {
		base = base[i+1:]
	}
	// Strip common Go binary suffixes generated by "go run" / "go test".
	for _, suffix := range []string{".test", ".exe"} {
		base = strings.TrimSuffix(base, suffix)
	}
	// Match buaaconnect, zju-connect, or the test binary name.
	for _, candidate := range []string{"buaaconnect", "zju-connect", "buaa"} {
		if strings.Contains(strings.ToLower(base), candidate) {
			return candidate
		}
	}
	return base
}

func sameProgramName(a, b string) bool {
	if a == "" || b == "" {
		return false
	}
	fieldsA := strings.Fields(a)
	fieldsB := strings.Fields(b)
	if len(fieldsA) == 0 || len(fieldsB) == 0 {
		return false
	}
	baseA := strings.ToLower(fieldsA[0])
	baseB := strings.ToLower(fieldsB[0])
	for _, candidate := range []string{"buaaconnect", "zju-connect", "buaa"} {
		if strings.Contains(baseA, candidate) && strings.Contains(baseB, candidate) {
			return true
		}
	}
	return baseA == baseB
}
